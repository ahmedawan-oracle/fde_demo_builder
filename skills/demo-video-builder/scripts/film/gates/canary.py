_SCENE = '''<!doctype html><html><head><meta charset="utf-8"><style>
html,body{margin:0;background:#082A34;width:1280px;height:720px;overflow:hidden;font-family:Arial,sans-serif}
body.pre #stage{visibility:hidden}
#stage{position:absolute;inset:0;background:linear-gradient(180deg,#082A34,#204A56)}
#box{position:absolute;left:100px;top:200px;width:300px;height:200px;background:#E56B5E;color:#fff;font-size:40px;will-change:transform}
#odo{position:absolute;left:600px;top:300px;color:#E9F3F9;font-size:60px}
</style></head><body><div id="stage"><div id="box">Acme</div><div id="odo"></div></div>
<script>
'use strict';
const RENDER = /[?&]render/.test(location.search);
if (RENDER) document.body.classList.add('pre');
%s
function frame(t) {
  document.getElementById('box').style.transform = 'translate(' + (t * 80).toFixed(2) + 'px,0) rotate(' + (t * 20).toFixed(2) + 'deg)';
  document.getElementById('odo').textContent = value(t);
}
window.__seek = t => { document.body.classList.remove('pre'); frame(t); };
window.__step = t => frame(t);
window.__total = 6;
</script></body></html>'''
GOOD_VALUE = "function value(t) { return Math.round(t * 1000).toLocaleString('en-US'); }"
# the classic seam bug: state that advances per CALL instead of being computed from t (pos += speed each frame)
BAD_VALUE = "let pos = 0; function value(t) { pos += 2; return pos.toLocaleString('en-US'); }"


def selftest():
    d = tempfile.mkdtemp(prefix='canary_selftest_')
    os.makedirs(os.path.join(d, 'scenes'))
    good, bad = os.path.join(d, 'scenes', 'good.html'), os.path.join(d, 'scenes', 'bad.html')
    open(good, 'w', encoding='utf-8').write(_SCENE % GOOD_VALUE)
    open(bad, 'w', encoding='utf-8').write(_SCENE % BAD_VALUE)
    times = default_times(6.0, 30, 3, cuts=[2.0], max_times=3)
    print('selftest  times %s' % times)
    rg = run_canary(good, times, os.path.join(d, 'out', 'good'), project=d)
    print('selftest  good: determinism %s  parity %s  chrome %s' % (rg['determinism'], rg['parity'], rg['chrome']))
    # per-call state: both cold runs draw the same (one call each) so run-to-run passes, but the stepped path has
    # advanced 30 more times when it reaches t — exactly what a worker seam looks like
    rb = run_canary(bad, times, os.path.join(d, 'out', 'bad'), project=d)
    print('selftest  bad : determinism %s  parity %s  (expect True / False)' % (rb['determinism'], rb['parity']))
    ok = rg['ok'] and rb['determinism'] and not rb['parity']
    bad_row = next((r for r in rb['per_time'] if not r['parity']), None)
    if bad_row:
        print('selftest  bad diff: %s' % bad_row.get('parity_diff'))
    shutil.rmtree(d, ignore_errors=True)
    print('selftest  ' + ('PASS' if ok else 'FAIL'))
    return ok


def main(argv):
    if '--selftest' in argv:
        return 0 if selftest() else 1
    args = [a for a in argv if not a.startswith('--')]
    def opt(name, default=None):
        if name in argv and argv.index(name) + 1 < len(argv):
            v = argv[argv.index(name) + 1]
            if v in args:
                args.remove(v)
            return v
        return default
    out = opt('--out', 'out/canary'); fps = int(opt('--fps', 30)); workers = int(opt('--workers', 3))
    dur = opt('--dur'); times = opt('--times'); approach = float(opt('--approach', 1.0))
    if not args:
        print(__doc__.split('\n\n')[0]); return 2
    scene = args[0]
    project = os.path.dirname(os.path.dirname(os.path.abspath(scene)))
    if times:
        times = [snap(float(x), fps) for x in times.split(',') if x.strip()]
    else:
        if not dur:
            tl = os.path.join(project, 'out', 'timeline.json')
            dur = json.load(open(tl))['total'] + 1.2 if os.path.exists(tl) else 10.0
        cuts = []
        tl = os.path.join(project, 'out', 'timeline.json')
        if os.path.exists(tl):
            cuts = json.load(open(tl)).get('cuts', [])
        times = default_times(float(dur), fps, workers, cuts)
    rep = run_canary(scene, times, out, fps=fps, approach=approach, cross_machine='--cross-machine' in argv, project=project)
    if '--json' in argv:
        print(json.dumps(rep, indent=1, default=str))
    else:
        print('canary  chrome %s  %d times: %s' % (rep['chrome'], len(rep['times']), ', '.join('%.2f' % t for t in rep['times'])))
        for r in rep['per_time']:
            print('  t=%6.2f  run-to-run %-5s cold-vs-stepped %-5s %s' % (r['t'], r['run_to_run_kind'], r['parity_kind'],
                  '' if r['parity_kind'] == 'same' else str(r.get('parity_diff'))))
        for e in rep['errors']:
            print('  ' + e)
        print('determinism %s | seek parity %s -> %s' % ('PASS' if rep['determinism'] else 'FAIL', 'PASS' if rep['parity'] else 'FAIL', out))
    return 0 if rep['ok'] else 1


if __name__ == '__main__':
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    sys.exit(main(sys.argv[1:]))
